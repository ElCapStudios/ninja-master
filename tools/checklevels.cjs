function countFeatures(rows) {
  const H = rows.length, W = rows[0].length;
  let n = 0;
  const seen = {};
  function at(x, y) { return (x < 0 || y < 0 || x >= W || y >= H) ? '#' : rows[y][x]; }
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (at(x, y) !== 'o' || seen[y + ':' + x]) continue;
      n++;
      const stack = [[x, y]];
      while (stack.length) {
        const p = stack.pop();
        const k = p[1] + ':' + p[0];
        if (seen[k]) continue;
        seen[k] = true;
        [[1, 0], [-1, 0], [0, 1], [0, -1]].forEach(function (d) {
          const xx = p[0] + d[0], yy = p[1] + d[1];
          if (at(xx, yy) === 'o' && !seen[yy + ':' + xx]) stack.push([xx, yy]);
        });
      }
    }
  }
  '=^~/%|'.split('').forEach(function (ch) {
    for (let y = 0; y < H; y++) {
      let run = false;
      for (let x = 0; x < W; x++) {
        const on = at(x, y) === ch;
        if (on && !run) n++;
        run = on;
      }
    }
  });
  let inGap = false, lastTop = null;
  for (let x = 0; x < W; x++) {
    let top = null;
    for (let y = 0; y < H; y++) if (SOLID_SET.indexOf(at(x, y)) >= 0) { top = y; break; }
    const gap = top === null;
    if (gap && !inGap) n++;
    inGap = gap;
    if (top !== null && lastTop !== null && top !== lastTop) n++;
    if (top !== null) lastTop = top;
  }
  n += findAll(toGrid(rows), ALL_ENEMY_CH + ALL_BOSS_CH + 'THM*BRkg123456+').length;
  return n;
}

