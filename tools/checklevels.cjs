// read the file
// ---------------------------------------------------------------------------

const src = fs.readFileSync(FILE, 'utf8');
if (src.indexOf('/* Generated by tools/genlevels.cjs - do not edit by hand. */') !== 0) {
  console.error('levels.js does not start with the right header line');
  process.exit(1);
}
let LEVELS;
try {
  LEVELS = new Function(src + '\nreturn LEVELS;')();
} catch (err) {
  console.error('levels.js will not parse: ' + err.message);
  process.exit(1);
}
if (!Array.isArray(LEVELS)) {
  console.error('LEVELS is not a list');
  process.exit(1);
}

