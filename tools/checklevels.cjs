function checkOne(level, index) {
  const bad = [];
  function say(m) { bad.push(m); }

  if (!level || !Array.isArray(level.rows) || !level.rows.length) {
    say('has no rows');
    return bad;
  }
  const rows = level.rows;
  const H = rows.length;
  const W = rows[0].length;
  const grid = toGrid(rows);

  const world = Math.floor(index / 6);
  const inWorld = index % 6;
  const wantBoss = inWorld === 5;
  const wantKind = (inWorld === 2 || inWorld === 4) ? 'maze' : 'run';
  const wantH = wantKind === 'run' ? RUN_H : ((inWorld === 4 && world >= 4) ? 51 : 34);

  if (typeof level.name !== 'string' || !level.name.length) say('has no name');
  if (level.world !== world) say('says world ' + level.world + ', slot says ' + world);
  if (level.boss !== wantBoss) say('says boss ' + level.boss + ', slot says ' + wantBoss);
  if (level.kind !== wantKind) say('says kind ' + level.kind + ', slot says ' + wantKind);
  if (H !== wantH) say('has ' + H + ' rows, slot wants ' + wantH);

  rows.forEach(function (row, y) {
    if (typeof row !== 'string') say('row ' + y + ' is not text');
    else if (row.length !== W) say('row ' + y + ' is ' + row.length + ' wide, wanted ' + W);
  });
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (LEGAL.indexOf(rows[y][x]) < 0) say('odd letter "' + rows[y][x] + '" at ' + x + ',' + y);
    }
  }
  if (bad.length) return bad;

  const kind = level.kind;
  const boss = level.boss;

  if (kind === 'run') {
    if (boss) { if (W < 90 || W > 130) say('boss width ' + W + ', wanted 90 to 130'); }
    else if (W < 160 || W > 240) say('run width ' + W + ', wanted 160 to 240');
  } else {
    if (W < 90 || W > 150) say('maze width ' + W + ', wanted 90 to 150');
    if (W % ROOM_W !== 0) say('maze width must divide by ' + ROOM_W);
    if (H % ROOM_H !== 0) say('maze height must divide by ' + ROOM_H);
  }

  const starts = findAll(grid, 'P');
  const flags = findAll(grid, 'F');
  const gems = findAll(grid, 'g');
  if (starts.length !== 1) say('wants one P, found ' + starts.length);
  if (flags.length !== 1) say('wants one F, found ' + flags.length);
  if (gems.length !== 3) say('wants three gems, found ' + gems.length);

  findAll(grid, ALL_ENEMY_CH).forEach(function (e) {
    if (ENEMIES[world].indexOf(e.ch) < 0) say('enemy "' + e.ch + '" is not from world ' + world);
  });
  const bossHere = findAll(grid, ALL_BOSS_CH);
  if (boss) {
    if (bossHere.length !== 1) say('boss level wants one boss, found ' + bossHere.length);
    else if (bossHere[0].ch !== BOSSES[world]) say('wrong boss letter for world ' + world);
  } else if (bossHere.length) say('a normal level must have no boss');

  findAll(grid, ALL_ENEMY_CH + ALL_BOSS_CH).forEach(function (e) {
    const under = e.y + 1 < H ? rows[e.y + 1][e.x] : '.';
    if (SOLID_SET.indexOf(under) < 0) say('"' + e.ch + '" at ' + e.x + ',' + e.y + ' stands on nothing');
  });

  if (LAVA_WORLDS.indexOf(world) < 0 && findAll(grid, '~').length) {
    say('world ' + world + ' must have no lava or deep water');
  }

  findAll(grid, 'T').forEach(function (t) {
    for (let i = 1; i <= 7; i++) {
      const c = t.y - i >= 0 ? rows[t.y - i][t.x] : '#';
      if (SOLID_SET.indexOf(c) >= 0) say('spring at ' + t.x + ',' + t.y + ' is blocked above');
    }
  });

  const stars = findAll(grid, '*');
  if (kind === 'run') {
    if (stars.length !== 1) say('a run level wants one star, found ' + stars.length);
    stars.forEach(function (st) {
      const part = st.x / W;
      if (part < 0.35 || part > 0.55) {
        say('star at ' + st.x + ' is ' + Math.round(part * 100) + ' percent in, wanted 35 to 55');
      }
    });
  } else if (stars.length > 1) say('a maze wants at most one star');

  const weapons = findAll(grid, '123456');
  if (weapons.length < 1 || weapons.length > 2) say('wants 1 or 2 weapons, found ' + weapons.length);
  if (kind === 'run') {
    weapons.forEach(function (wp) {
      if (wp.x > W * 0.68) say('weapon at ' + wp.x + ' is past the first two thirds');
    });
  }

  const coins = findAll(grid, 'o').length;
  const foes = findAll(grid, ALL_ENEMY_CH).length;
  if (kind === 'run' && !boss) {
    if (coins < 30 || coins > 60) say('wants 30 to 60 coins, found ' + coins);
    if (foes < 12 || foes > 22) say('wants 12 to 22 enemies, found ' + foes);
  } else if (kind === 'maze') {
    if (coins < 25 || coins > 50) say('wants 25 to 50 coins, found ' + coins);
    if (foes < 10 || foes > 20) say('wants 10 to 20 enemies, found ' + foes);
  } else {
    if (coins < 10 || coins > 40) say('boss level wants 10 to 40 coins, found ' + coins);
    if (foes < 2 || foes > 8) say('boss level wants 2 to 8 enemies, found ' + foes);
  }

  if (kind === 'run') {
    let run = 0;
    for (let x = 0; x <= W; x++) {
      let hard = false;
      if (x < W) for (let y = 0; y < H; y++) if (SOLID_SET.indexOf(rows[y][x]) >= 0) hard = true;
      if (x < W && !hard) run++;
      else { if (run > 4) say('a hole of ' + run + ' columns ends at ' + x); run = 0; }
    }
    const feats = countFeatures(rows);
    if (W / feats > 4) say('one thing to do only every ' + (W / feats).toFixed(1) + ' columns');
    if (world >= 1 && !boss && !findAll(grid, 'T').length) say('wants at least one spring');
  }

  if (boss && bossHere.length === 1) {
    const b = bossHere[0];
    function plainCol(x) {
      if (x < 1 || x >= W - 1) return false;
      for (let y = 0; y < H; y++) {
        const c = rows[y][x];
        if (y >= RUN_FLOOR) { if (c !== '#') return false; continue; }
        if (c === '.' || c === 'o' || c === b.ch) continue;
        return false;
      }
      return true;
    }
    let left = b.x, right = b.x;
    while (plainCol(left - 1)) left--;
    while (plainCol(right + 1)) right++;
    if (right - left + 1 < 26) say('boss arena is ' + (right - left + 1) + ' columns, wanted 26');
    if (flags.length && flags[0].x < right) say('the flag must be past the arena');
    gems.forEach(function (g) { if (g.x > left) say('gem at ' + g.x + ' is not before the arena'); });
  }

  if (starts.length !== 1 || flags.length !== 1) return bad;

  const solve = analyse(rows);
  if (!solve) { say('no start or no flag'); return bad; }
  if (!solve.ok) say('the solver cannot reach the flag');
  gems.forEach(function (g) {
    if (!solve.ok) return;
    if (!solve.reachable(g.x, g.y)) say('gem at ' + g.x + ',' + g.y + ' cannot be reached');
    else if (!solve.detour(g.x, g.y)) say('gem at ' + g.x + ',' + g.y + ' sits on the main path');
  });

  const traps = solve.traps();
  if (traps.length) {
    say('has ' + traps.length + ' dead end spots, first few: ' + traps.slice(0, 6).join(' '));
  }

  if (kind === 'maze') {
    for (let x = 0; x < W; x++) {
      if (rows[0][x] !== '#') say('top border leaks at ' + x);
      if (rows[H - 1][x] !== '#') say('bottom border leaks at ' + x);
    }
    for (let y = 0; y < H; y++) {
      if (rows[y][0] !== '#') say('left border leaks at ' + y);
      if (rows[y][W - 1] !== '#') say('right border leaks at ' + y);
    }

    const keys = findAll(grid, 'k');
    if (keys.length !== 1) say('a maze wants one key, found ' + keys.length);
    const doorGroups = groupCount(grid, '+');
    if (doorGroups < 1 || doorGroups > 2) say('a maze wants 1 or 2 doors, found ' + doorGroups);
    if (!findAll(grid, '%').length) say('a maze wants a fake wall');

    if (keys.length === 1) {
      const noKey = analyse(rows, { allowKey: false });
      if (!solve.reachable(keys[0].x, keys[0].y)) say('the key cannot be reached');
      if (noKey && !noKey.reachable(keys[0].x, keys[0].y)) say('the key sits behind the door');
      if (noKey && noKey.ok) say('the flag can be reached without the key');
    }

    const C = W / ROOM_W, R = H / ROOM_H;
    const g = roomGraph(rows, C, R);
    const startRoom = roomOf(starts[0].x, starts[0].y);
    const flagRoom = roomOf(flags[0].x, flags[0].y);
    const dist = bfsRooms(g.adj, startRoom);
    g.nodes.forEach(function (n) { if (dist[n] === undefined) say('room ' + n + ' is cut off'); });
    let far = 0;
    g.nodes.forEach(function (n) { if (dist[n] !== undefined && dist[n] > far) far = dist[n]; });
    if (dist[flagRoom] !== far) {
      say('flag room is ' + dist[flagRoom] + ' rooms away, the furthest is ' + far);
    }
    const distFlag = bfsRooms(g.adj, flagRoom);
    const main = {};
    g.nodes.forEach(function (n) {
      if (dist[n] !== undefined && dist[n] + distFlag[n] === dist[flagRoom]) main[n] = true;
    });
    let deep = 0;
    g.nodes.forEach(function (n) {
      if (main[n] || g.adj[n].length !== 1) return;
      let d = 0, cur = n, prev = null;
      while (!main[cur] && d < 60) {
        const nxt = g.adj[cur].filter(function (m) { return m !== prev; })[0];
        if (!nxt) break;
        prev = cur; cur = nxt; d++;
      }
      if (d >= 2) deep++;
    });
    if (deep < 2) say('wants two dead ends two or more rooms deep, found ' + deep);

    const perRoom = {};
    findAll(grid, ALL_ENEMY_CH).forEach(function (e) {
      const k = roomOf(e.x, e.y);
      perRoom[k] = (perRoom[k] || 0) + 1;
    });
    Object.keys(perRoom).forEach(function (k) {
      if (perRoom[k] > 3) say('room ' + k + ' holds ' + perRoom[k] + ' enemies');
    });
  }

  return bad;
}

